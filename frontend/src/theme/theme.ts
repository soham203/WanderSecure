// Safety Score Color Helper
export const getSafetyScoreColor = (score: string): string => {
  switch (score.toLowerCase()) {
    case 'low':
      return colors.safety.low;
    case 'medium':
      return colors.safety.medium;
    case 'high':
      return colors.safety.high;
    case 'critical':
      return colors.safety.critical;
    default:
      return colors.safety.medium;
  }
};

// Alert Priority Color Helper
export const getAlertPriorityColor = (priority: string): string => {
  switch (priority.toLowerCase()) {
    case 'low':
      return colors.info[500];
    case 'medium':
      return colors.warning[500];
    case 'high':
      return colors.error[500];
    case 'critical':
      return colors.error[700];
    default:
      return colors.info[500];
  }
};
